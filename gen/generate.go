package gen

import (
	"embed"
	"fmt"
	"net/http"
	"os"
	"path/filepath"
	"reflect"

	"github.com/mxcd/home/pkg/livewire"
)

//go:embed runtime/*.ts
var runtime embed.FS

// Options says where the output goes.
type Options struct {
	// TSDir receives types.ts, api.ts and the runtime files.
	TSDir string
	// OpenAPIFile receives the OpenAPI 3.1 document; skipped when empty.
	OpenAPIFile string
	Title       string
	Version     string
	// BasePath is the API base the routes are mounted under, e.g. "/api/v1".
	BasePath string
}

// Generate writes the TypeScript client and the OpenAPI document for a registry.
func Generate(registry *livewire.Registry, options Options) error {
	ts := &types{byName: map[string]reflect.Type{}}
	for _, res := range registry.Resources {
		ts.add(res.DTO)
	}
	for _, m := range registry.Mutations {
		if m.HasBody() {
			ts.add(m.Request)
		}
		if m.Status() != http.StatusNoContent {
			ts.add(m.Response)
		}
	}
	ts.add(reflect.TypeFor[livewire.Error]())

	if err := os.MkdirAll(options.TSDir, 0o755); err != nil {
		return err
	}
	files := map[string]string{
		"types.ts": typescriptTypes(ts),
		"api.ts":   typescriptAPI(registry),
	}
	entries, err := runtime.ReadDir("runtime")
	if err != nil {
		return err
	}
	for _, entry := range entries {
		content, err := runtime.ReadFile("runtime/" + entry.Name())
		if err != nil {
			return err
		}
		files[entry.Name()] = generatedHeader + string(content)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(options.TSDir, name), []byte(content), 0o644); err != nil {
			return err
		}
	}
	if options.OpenAPIFile != "" {
		document, err := openAPI(registry, ts, options)
		if err != nil {
			return fmt.Errorf("gen: openapi: %w", err)
		}
		if err := os.WriteFile(options.OpenAPIFile, document, 0o644); err != nil {
			return err
		}
	}
	return nil
}

const generatedHeader = "// Code generated by livewire/gen. DO NOT EDIT.\n\n"
